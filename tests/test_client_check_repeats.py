"""
Offline tests for the --repeats setting of scripts/client_check.py. No network, no keys:
ENGINES is replaced with stub callables that return canned answers. Runs under pytest or
directly:

    python -I -X utf8 -m pytest tests/test_client_check_repeats.py -q
    python -I -X utf8 tests/test_client_check_repeats.py

Three things are proved here:
  1. With the default (and with --repeats 1) the output is byte-identical to a fixture that
     was generated by the code as it stood BEFORE the repeats setting existed
     (tests/fixtures/client_check_n1/expected and expected_fail).
  2. With --repeats 3 and stubs that name the client in 2 of 3 runs, the receipt says
     "named in 2 of 3 runs", every run has its own file, SHA-256 and first three businesses.
  3. A stubbed failure is reported as failed and is never counted as "not named".
"""
import hashlib
import json
import os
import shutil
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "scripts"))

import client_check as cc  # noqa: E402

FIX = os.path.join(HERE, "fixtures", "client_check_n1")
ENGS = ("perplexity", "gemini", "openai", "anthropic")
RUN_DATE = "2026-10-27"

# The same stub answers the fixture was generated with (do not edit without regenerating it).
FIXTURE_TEXTS = {
    "best roofing company in Springfield MO":
        "**Acme Roofing** is a strong pick, then **Zed Roofing** and **Orbit Roofing**.\n",
    "best law firm in Oklahoma City":
        "**Crowe & Dunlevy** leads. Also **Doerner Saunders Daniel & Anderson** and **McAfee & Taft**.\n",
}


def fixture_ok(engine):
    def fn(prompt):
        cc.LAST_CALL_META[engine] = {"served_model": engine + "-model-x",
                                     "usage": {"input_tokens": 7, "output_tokens": 11}}
        return True, FIXTURE_TEXTS[prompt] + "Answer by " + engine + " — café.", [], ""
    return fn


def run_cli(engines_map, argv_extra=(), inp=None, engines_arg=None):
    """Run cc.main in a temp working directory with relative paths (so the receipt text is
    reproducible), restore cwd and ENGINES, return (rc, run_dir, {file name: text})."""
    tmp = tempfile.mkdtemp()
    shutil.copy(inp or os.path.join(FIX, "in.json"), os.path.join(tmp, "in.json"))
    old_cwd, old_eng = os.getcwd(), cc.ENGINES
    cc.ENGINES = engines_map
    os.chdir(tmp)
    try:
        argv = ["--input", "in.json", "--outdir", "client_checks", "--run-date", RUN_DATE]
        if engines_arg:
            argv += ["--engines", engines_arg]
        rc = cc.main(argv + list(argv_extra))
    finally:
        os.chdir(old_cwd)
        cc.ENGINES = old_eng
    d = os.path.join(tmp, "client_checks", RUN_DATE)
    files = {}
    if os.path.isdir(d):
        for n in os.listdir(d):
            with open(os.path.join(d, n), "rb") as f:
                files[n] = f.read()
    return rc, d, files


def read_fixture(sub):
    d = os.path.join(FIX, sub)
    out = {}
    for n in os.listdir(d):
        with open(os.path.join(d, n), "rb") as f:
            out[n] = f.read()
    return out


# ------------------------------------------------------------ N=1 unchanged


def _fixture_fail_map():
    m = {e: fixture_ok(e) for e in ENGS}
    m["gemini"] = lambda p: (False, "", [], "QUOTA: gemini HTTP 429: slow down")

    def boom(p):
        raise RuntimeError("boom")
    m["openai"] = boom
    return m


def test_n1_default_output_is_byte_identical_to_fixture():
    rc, _, files = run_cli({e: fixture_ok(e) for e in ENGS})
    assert rc == 0
    want = read_fixture("expected")
    assert sorted(files) == sorted(want)
    for n in want:
        assert files[n] == want[n], "differs from fixture: " + n


def test_n1_explicit_repeats_1_is_byte_identical_to_fixture():
    rc, _, files = run_cli({e: fixture_ok(e) for e in ENGS}, ["--repeats", "1"])
    assert rc == 0 and files == read_fixture("expected")


def test_n1_failure_path_is_byte_identical_to_fixture():
    rc, _, files = run_cli(_fixture_fail_map())
    assert rc == 0 and files == read_fixture("expected_fail")


def test_n1_rows_have_no_repeat_fields():
    _, _, files = run_cli({e: fixture_ok(e) for e in ENGS})
    row = json.loads(files["T-01-alpha_openai.json"])
    assert row["run"] == 1 and "repeats_requested" not in row
    assert "repeats_per_engine" not in json.loads(files["SUMMARY.json"])
    assert b"Repeats" not in files["RECEIPT.md"]
    assert not [n for n in files if "_run" in n]


# ------------------------------------------------------------ N=3, named in 2 of 3


def scripted(engine, script):
    """Stub engine: call k (1-based, per prompt) returns script[k-1] = (ok, text_or_error).
    Records the prompts it was sent so the test can prove the request was identical."""
    seen = {}
    prompts = []

    def fn(prompt):
        prompts.append(prompt)
        k = seen[prompt] = seen.get(prompt, 0) + 1
        ok, payload = script[k - 1]
        if not ok:
            return False, "", [], payload
        cc.LAST_CALL_META[engine] = {"served_model": engine + "-m", "usage": {"input_tokens": 5, "output_tokens": 9}}
        return True, payload, [], ""
    fn.prompts = prompts
    return fn



# run 1 and 3 name Acme Roofing, run 2 does not; each run lists different businesses
NAMED_2_OF_3 = [
    (True, "**Acme Roofing** first, then **Zed Roofing**, **Orbit Roofing** and **Delta Roofing**.\n"),
    (True, "**Peak Roofing** leads, then **Zed Roofing** and **Summit Roofing**.\n"),
    (True, "**Orbit Roofing** is listed, then **Acme Roofing** and **Birch Roofing**.\n"),
]


def one_item_file():
    p = os.path.join(tempfile.mkdtemp(), "in_one.json")
    with open(os.path.join(FIX, "in.json"), encoding="utf-8") as f:
        items = json.load(f)
    with open(p, "w", encoding="utf-8") as f:
        json.dump(items[:1], f)
    return p


def test_n3_named_in_2_of_3_runs():
    stubs = {e: scripted(e, NAMED_2_OF_3) for e in ENGS}
    rc, d, files = run_cli(stubs, ["--repeats", "3"], inp=one_item_file(), engines_arg="openai,anthropic")
    assert rc == 0
    # every run is saved: run 1 keeps the old name, runs 2 and 3 get _run<k>
    for e in ("openai", "anthropic"):
        for k, suffix in ((1, ""), (2, "_run2"), (3, "_run3")):
            name = "T-01-alpha_%s%s.json" % (e, suffix)
            assert name in files, name
            row = json.loads(files[name])
            assert row["run"] == k and row["repeats_requested"] == 3 and row["run_status"] == "OK"
            assert row["answer_sha256"] == hashlib.sha256(row["answer_verbatim"].encode("utf-8")).hexdigest()
            assert row["answer_verbatim"] == NAMED_2_OF_3[k - 1][1]
            assert row["client_named"] is (k != 2)
        # the same identical question went out three times
        assert stubs[e].prompts == ["best roofing company in Springfield MO"] * 3
    shas = {json.loads(files["T-01-alpha_openai%s.json" % s])["answer_sha256"] for s in ("", "_run2", "_run3")}
    assert len(shas) == 3                          # three different answers, three different hashes
    rec = files["RECEIPT.md"].decode("utf-8")
    for e in ("openai", "anthropic"):               # exact and loose columns, runs answered, runs failed
        assert "| %s | named in 2 of 3 runs | named in 2 of 3 runs | 3 | 0 |" % e in rec
    assert "Repeats per engine: 3" in rec
    assert "Requests: 6 | OK: 6 | FAIL: 0" in rec
    # first three businesses per run, in each run's own order
    assert "Acme Roofing; Zed Roofing; Orbit Roofing" in rec
    assert "Peak Roofing; Zed Roofing; Summit Roofing" in rec
    assert "Orbit Roofing; Acme Roofing; Birch Roofing" in rec
    for k in (1, 2, 3):
        assert "| openai | %d | OK |" % k in rec
    assert "Answer by" not in rec and "leads, then" not in rec     # raw text stays out of the receipt
    s = json.loads(files["SUMMARY.json"])
    assert s["repeats_per_engine"] == 3 and s["requests"] == 6 and s["ok"] == 6
    t = s["results"][0]["engines"]["openai"]
    assert t["named_in"]["exact"] == 2 and t["named_in"]["answered"] == 3 and t["named_in"]["failed"] == 0
    assert t["named_in"]["text_exact"] == "named in 2 of 3 runs"
    assert [r["run"] for r in t["runs"]] == [1, 2, 3]
    assert [r["client_named"] for r in t["runs"]] == [True, False, True]
    assert t["runs"][1]["first_three_named"][0] == "Peak Roofing"


# ------------------------------------------------------------ failures are failures


def test_n3_failed_run_is_failed_not_unnamed():
    # gemini: named, FAILED, not named  -> "1 of 2 answered", never "1 of 3"
    # openai: FAILED x3                 -> all runs failed, never "0 of 3"
    # anthropic: named, FAILED, named   -> "2 of 2 answered, 1 failed", never "2 of 3 runs"
    stubs = {
        "gemini": scripted("gemini", [NAMED_2_OF_3[0], (False, "QUOTA: gemini HTTP 429: slow down"), NAMED_2_OF_3[1]]),
        "openai": scripted("openai", [(False, "openai HTTP 500: x")] * 3),
        "anthropic": scripted("anthropic", [NAMED_2_OF_3[0], (False, "EngineError: timeout"), NAMED_2_OF_3[2]]),
        "perplexity": scripted("perplexity", NAMED_2_OF_3),
    }
    rc, d, files = run_cli(stubs, ["--repeats", "3"], inp=one_item_file())
    assert rc == 0
    rec = files["RECEIPT.md"].decode("utf-8")
    assert "| gemini | named in 1 of 2 answered runs (1 of 3 runs FAILED, not counted as not named)" in rec
    assert "| anthropic | named in 2 of 2 answered runs (1 of 3 runs FAILED, not counted as not named)" in rec
    assert "| openai | no answer: all 3 runs failed | no answer: all 3 runs failed | 0 | 3 |" in rec
    assert "| perplexity | named in 2 of 3 runs |" in rec
    assert "named in 1 of 3" not in rec and "named in 0 of 3" not in rec and "named in 2 of 3 runs (" not in rec
    # the failed run rows carry no answer and are marked FAIL with their error class
    g2 = json.loads(files["T-01-alpha_gemini_run2.json"])
    assert g2["run_status"] == "FAIL" and g2["error_class"] == "QuotaBlocked"
    assert g2["answer_verbatim"] == "" and g2["answer_sha256"] is None
    assert g2["client_named"] is None and g2["client_named_loose"] is None and g2["first_three_named"] == []
    assert "| gemini | 2 | FAIL (QuotaBlocked) | n/a | n/a | n/a |" in rec
    # one file per run even for the engine that failed every time
    for suffix in ("", "_run2", "_run3"):
        assert json.loads(files["T-01-alpha_openai%s.json" % suffix])["run_status"] == "FAIL"
    s = json.loads(files["SUMMARY.json"])
    assert s["requests"] == 12 and s["ok"] == 7 and s["fail"] == 5
    eng = s["results"][0]["engines"]
    assert eng["gemini"]["named_in"]["answered"] == 2 and eng["gemini"]["named_in"]["failed"] == 1
    assert eng["gemini"]["named_in"]["exact"] == 1
    assert eng["openai"]["named_in"]["answered"] == 0 and eng["openai"]["named_in"]["exact"] == 0
    assert eng["gemini"]["runs"][1]["run_status"] == "FAIL" and eng["gemini"]["runs"][1]["client_named"] is None
    # one engine failing never blocks the others
    assert eng["perplexity"]["named_in"]["failed"] == 0


