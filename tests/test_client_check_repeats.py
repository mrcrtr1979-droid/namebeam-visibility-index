def test_repeats_validation_and_dry_run():
    tmp = tempfile.mkdtemp()
    inp = os.path.join(tmp, "in.json")
    shutil.copy(os.path.join(FIX, "in.json"), inp)
    out = os.path.join(tmp, "o")
    for bad in ("0", "-1", "11"):
        assert cc.main(["--input", inp, "--outdir", out, "--repeats", bad]) == 2
    try:
        cc.main(["--input", inp, "--outdir", out, "--repeats", "two"])
        raise AssertionError("argparse should reject a non-number")
    except SystemExit as exc:
        assert exc.code == 2
    assert not os.path.exists(out)
    called = []
    old = cc.ENGINES
    cc.ENGINES = {e: (lambda p, e=e: called.append(e)) for e in ENGS}
    try:
        rc = cc.main(["--input", inp, "--outdir", out, "--repeats", "3", "--dry-run"])
    finally:
        cc.ENGINES = old
    assert rc == 0 and not called and not os.path.exists(out)


